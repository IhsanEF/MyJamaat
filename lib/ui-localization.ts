export function uiRoleLabel(locale:UiLocale,role:string):string {
  if(locale==="en-CA")return role;
  let result=role;
  for(const name of Object.keys(roleCopyKeys).sort((a,b)=>b.length-a.length))result=result.replace(name,uiText(locale,roleCopyKeys[name]));
  return result;
}

