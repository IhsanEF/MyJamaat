function pseudo(text:string,rtl:boolean):string {
  const expanded=text.replace(/[A-Za-z]/g,char=>{const lower=accents[char.toLowerCase()]||char;return char===char.toUpperCase()?lower.toUpperCase():lower;}).replace(/([aeiouáëïöü])/gi,"$1$1");
  return rtl?`⟦مرحبا ${expanded}⟧`:`⟦${expanded}⟧`;
}

