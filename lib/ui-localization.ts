export function uiChoiceLabel(locale:UiLocale,label:string):string {const key=choiceCopyKeys[label];return key?uiText(locale,key):label;}
export function uiSelectOptionLabel(locale:UiLocale,value:string,label:string):string {
  // User-authored person and place names stay verbatim even when they match an English choice.
  if(/^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i.test(value))return label;
  if(value===label&&statusCopyKeys[value])return uiStatusLabel(locale,value);
  return uiChoiceLabel(locale,label);
}

