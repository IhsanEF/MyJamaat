export function formatUiDateTime(value:string|Date,locale:UiLocale,zone:string):string {
  const date=value instanceof Date?value:new Date(value);
  if(Number.isNaN(date.getTime()))return "";
  return displayScheduleDate(date.toISOString(),zone,true,locale);
}
